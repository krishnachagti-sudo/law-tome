// Joins a book's round drafts into one manuscript (QA notes stripped) and one
// QA log (every entry's QA note, with the checks it asks for pulled to the top).
//
//   node books/scripts/assemble.mjs books/true-or-folklore
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
const rounds = readdirSync(join(dir, 'drafts')).filter((f) => /^round-\d+\.md$/.test(f)).sort();
const front = readFileSync(join(dir, 'front-matter.md'), 'utf8').trim();
const back = readFileSync(join(dir, 'back-matter.md'), 'utf8').trim();

let manuscript = front + '\n\n';
const log = [];
for (const f of rounds) {
  const text = readFileSync(join(dir, 'drafts', f), 'utf8');
  manuscript += text.replace(/^> \*\*QA notes\.\*\*.*(\n>.*)*\n?/gm, '').replace(/<!--.*?-->\n/g, '').replace(/\n{3,}/g, '\n\n').trim() + '\n\n';
  for (const part of text.split(/<!--\s*slug:/).slice(1)) {
    const slug = part.split('|')[0].trim();
    const verdict = (part.match(/verdict:\s*(\w+)/) || [])[1];
    const title = (part.match(/^## (.*)$/m) || [])[1];
    const qa = (part.match(/^> \*\*QA notes\.\*\*(.*(?:\n>.*)*)/m) || [])[1] || '';
    log.push({ round: f.replace('.md', ''), slug, verdict, title, qa: qa.replace(/\n> ?/g, ' ').trim() });
  }
}
manuscript += back + '\n';
writeFileSync(join(dir, 'manuscript.md'), manuscript);

const legal = log.filter((e) => /LEGAL REVIEW/i.test(e.qa));
const source = log.filter((e) => /primary|Wikipedia|secondary|check|confirm|no date|undated|before print/i.test(e.qa));
let md = `# True or Folklore? — QA log\n\nGenerated by \`books/scripts/assemble.mjs\` from the round drafts. ${log.length} entries.\n\n`;
md += `- **Legal review:** ${legal.length} entries.\n- **Source to check before print:** ${source.length} entries.\n\n`;
md += `## Legal review\n\n${legal.map((e) => `- [ ] ${e.round} · ${e.slug} · ${e.title}`).join('\n')}\n\n`;
md += `## Every entry\n\n`;
for (const e of log) md += `### ${e.round} · ${e.title}\n\n\`${e.slug}\` · ${e.verdict}\n\n- [ ] Sources checked\n- [ ] Edited\n\n${e.qa}\n\n`;
writeFileSync(join(dir, 'QA-LOG.md'), md);
console.log(`${log.length} entries; manuscript ${manuscript.split(/\s+/).length} words; legal ${legal.length}; source checks ${source.length}`);
